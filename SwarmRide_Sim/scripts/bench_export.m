%% BENCH_EXPORT  Files the bench prototype needs from the simulation (writes to ../Bench_Prototype).
%   1. drive_files/*.csv   motion and commands for the test rig (one damper), 1 ms steps
%   2. firmware/include/sr_params_lhb.h   controller gains and drive constants for the firmware
%   3. firmware/test/vectors/*.csv        inputs and MATLAB outputs to check the C firmware
%   Run after check_bench (it needs results/bench_drive.mat).   >> run scripts/bench_export

bench_export_all(fileparts(fileparts(mfilename('fullpath'))));

function bench_export_all(root)
out = fullfile(fileparts(root), 'Bench_Prototype');
BD = load(fullfile(root, 'results', 'bench_drive.mat'));
[P, D, HW] = lhb_params(BD.U);
write_drive_files(fullfile(out, 'drive_files'), HW, BD.DR);
write_params_header(fullfile(out, 'firmware', 'include', 'sr_params_lhb.h'), P, D, HW);
write_vectors(fullfile(out, 'firmware', 'test', 'vectors'), P, HW);
fprintf('Wrote drive files, firmware parameters and test vectors to %s\n', out);
end

function [P, D, HW] = lhb_params(U)
% the prototype's vehicle: LHB crowded, 160 km/h, design C, controller C3 (runs the scripts in
% this function's own workspace, so no scenario variables leak in)
trainType = 'LHB'; designType = 'C'; trackType = 'poor'; v_kmh = 160; mload_t = 12; ctrlMode = 'C3'; %#ok<NASGU>
sr_params;
sr_params_stage3;
HW = bp_hardware(D, P, U);
HW.Vbank_min = P.Vmin;
end

function write_drive_files(dir, HW, DR)
if ~isfolder(dir), mkdir(dir); end
tests = {'emf', 'back_emf'; 'damping', 'damping_law'; 'step', 'current_step'; 'vlimit', 'voltage_limit'; ...
         'failsafe', 'fail_safe'; 'replay_poor', 'rough_track_C3'; 'replay_good', 'smooth_track_C3'; ...
         'replay_settle', 'settlement_push_C4'};
for k = 1:size(tests, 1)
    BX = bp_bench_profile(tests{k, 1}, HW, DR);
    M = [BX.t, 1e3 * BX.x, 1e3 * BX.v, BX.c, BX.F, BX.act, BX.fault];
    fh = fopen(fullfile(dir, [tests{k, 2} '.csv']), 'w');
    fprintf(fh, 'time_s,stroke_mm,speed_mm_per_s,damping_cmd_Ns_per_m,push_force_cmd_N,push_window,fault\n');
    fprintf(fh, '%.3f,%.4f,%.3f,%.1f,%.1f,%d,%d\n', M');
    fclose(fh);
end
end

function write_params_header(f, P, ~, HW)
K3 = sr_stage3_consts();
fh = fopen(f, 'w');
fprintf(fh, '/* sr_params_lhb.h - GENERATED by SwarmRide_Sim/scripts/bench_export.m. Do not edit by hand.\n');
fprintf(fh, ' * LHB coach, crowded design load, 160 km/h, damper design C, controller C3 (LPV + Train Brain preview).\n');
fprintf(fh, ' * The preview gains depend on speed: regenerate for each speed band.\n */\n');
fprintf(fh, '#ifndef SR_PARAMS_LHB_H\n#define SR_PARAMS_LHB_H\n\n');
d = @(name, val, cmt) fprintf(fh, '#define %-16s (%.10g) /* %s */\n', name, val, cmt);
d('SR_TC', K3.Tc, 'controller period [s]');
d('SR_NA', K3.Na, 'preview samples ahead of the lead wheel');
d('SR_NB', K3.Nb, 'preview samples behind the lead wheel');
d('SR_NP', K3.Np, 'preview samples in total');
d('SR_NL', K3.nL, 'load grid points');
d('SR_ND', P.nd, 'dampers per bogie');
d('SR_V', P.v, 'design speed of these gains [m/s]');
d('SR_EPS_V', P.eps_v, 'speed smoothing in c = F v / (v^2 + eps^2) [m/s]');
d('SR_C_CAP', P.c_cap, 'damping cap per bogie (efficiency limit) [N s/m]');
d('SR_C_FLOOR', P.c_floor, 'damping floor per bogie [N s/m]');
d('SR_C_OIL', P.c_oil, 'passive oil damping kept per bogie [N s/m]');
d('SR_TAU_C', P.tau_c, 'damping command smoothing [s]');
d('SR_KE', HW.Ke, 'machine constant per damper [V s/m]');
d('SR_RC', HW.Rc, 'equivalent DC resistance [ohm]');
d('SR_L', HW.L, 'equivalent DC inductance [H]');
d('SR_CMAX', HW.cmax, 'most damping per damper (coil shorted) [N s/m]');
d('SR_I_LIM', HW.i_lim, 'current limit [A]');
d('SR_TI', HW.Ti, 'current-control period [s]');
d('SR_TAU_CL', HW.tau_cl, 'designed current-loop time constant [s]');
d('SR_UMAX', HW.Umax, 'largest equivalent inverter voltage [V]');
d('SR_VBANK_MIN', HW.Vbank_min, 'fail-safe: bank voltage minimum [V]');
d('SR_T_TRIP', HW.T_trip, 'fail-safe: winding temperature trip [C]');
b = {'SR_CSC', P.Csc, 'supercapacitor [F]'; 'SR_VMAX', P.Vmax, 'supercap full [V]'; 'SR_VMIN', P.Vmin, 'supercap empty [V]';
     'SR_VCHG', P.Vchg, 'charge the battery above [V]'; 'SR_VDIS', P.Vdis, 'battery supports below [V]';
     'SR_SOCMIN', P.SOCmin, 'battery lowest state of charge'; 'SR_SOCMAX', P.SOCmax, 'battery highest state of charge'; 'SR_ETA_CH', P.eta_ch, 'battery charge efficiency'; 'SR_ETA_DIS', P.eta_dis, 'battery discharge efficiency';
     'SR_PCH_MAX', P.Pch_max, 'battery charge limit [W]'; 'SR_PDIS_MAX', P.Pdis_max, 'battery discharge limit [W]';
     'SR_KV', P.Kv, 'supervisor gain [W/V]'; 'SR_EBAT_WH', P.Ebat_Wh, 'battery [Wh]'};
for k = 1:size(b, 1), d(b{k, :}); end
fprintf(fh, '\n#ifdef SR_PARAMS_DEFINE_TABLES   /* defined in exactly one source file (sr_lpv.c) */\n');
fprintf(fh, '\n/* body mass at each load grid point [kg] */\n');
fprintf(fh, 'static const sr_real SR_KGRID_M[SR_NL] = {%s};\n', join_num(P.Kgrid_m));
fprintf(fh, '\n/* feedback gains: row l = load point, element r + 2 c = Kx(r, c) (2 x 8, column major) */\n');
fprintf(fh, 'static const sr_real SR_KX[SR_NL][16] = {\n');
for l = 1:size(P.Kx, 1), fprintf(fh, '  {%s},\n', join_num(P.Kx(l, :))); end
fprintf(fh, '};\n\n/* preview gains: element r + 2 j = Kp(r, j) (2 x NP, column major) */\n');
fprintf(fh, 'static const sr_real SR_KP[SR_NL][2 * SR_NP] = {\n');
for l = 1:size(P.Kp, 1), fprintf(fh, '  {%s},\n', join_num(P.Kp(l, :))); end
fprintf(fh, '};\n#endif /* SR_PARAMS_DEFINE_TABLES */\n\n#endif\n');
fclose(fh);
end

function s = join_num(v)
s = strjoin(arrayfun(@(x) sprintf('%.10g', x), v, 'UniformOutput', false), ', ');
end

function write_vectors(dir, P, HW)
if ~isfolder(dir), mkdir(dir); end
rng(42);
% 1. LPV state feedback + preview (the Simulink block's code)
N = 200;  Np = size(P.Kp, 2) / 2;
M = zeros(N, 1 + 8 + Np + 2);
for n = 1:N
    m_hat = P.Kgrid_m(1) + (P.Kgrid_m(end) - P.Kgrid_m(1)) * (1.2 * rand - 0.1);   % includes beyond the grid
    x = [0.01 0.002 0.005 0.005 0.1 0.02 0.05 0.05]' .* randn(8, 1);
    p = 0.003 * randn(Np, 1);
    F = lpv_force(x, p, m_hat, P);
    M(n, :) = [m_hat, x', p', F'];
end
writematrix(M, fullfile(dir, 'lpv.csv'));
% 2. semi-active conversion
N = 500;  M = zeros(N, 6);
for n = 1:N
    F = 5e3 * randn(2, 1);  v = 0.05 * randn(2, 1);
    c = F .* v ./ (v.^2 + P.eps_v^2) - P.c_oil;
    c = min(max(c, P.c_floor), P.c_cap);
    M(n, :) = [F', v', c'];
end
writematrix(M, fullfile(dir, 'semiactive.csv'));
% 3. drive: current reference, current controller, fail-safe
N = 1000;  M = zeros(N, 17);
for n = 1:N
    c = HW.c_req * 1.4 * rand;  F = 6e3 * randn;  act = double(rand < 0.3);  v = 0.15 * randn;
    i = 30 * randn;  z = 20 * randn;  fault = double(rand < 0.05);  Vb = 8 + 40 * rand;
    Tw = 40 + 100 * rand;  latch = double(rand < 0.1);
    if rand < 0.05, i = 1.3 * HW.i_lim * sign(randn); end
    iref = bp_current_ref(c, F, act, v, HW);
    [u, zn, sat] = bp_current_ctrl(iref, i, v, z, HW);
    [relay, ln, code] = bp_failsafe(fault, Vb, Tw, i, latch, HW);
    M(n, :) = [c, F, act, v, i, z, fault, Vb, Tw, latch, iref, u, zn, sat, relay, ln, code];
end
writematrix(M, fullfile(dir, 'drive.csv'));
% 4. bank supervisor (the Simulink energy-supervisor rules)
N = 1000;  M = zeros(N, 13);
for n = 1:N
    Esc = 0.5 * P.Csc * (10 + 40 * rand)^2;  SOC = rand;  Pdc = 200 * randn;  Pl = 8 + 20 * rand;  dt = 1e-3 * (1 + 9 * rand);
    if rand < 0.1, Esc = 0.5 * P.Csc * P.Vmax^2; end
    if rand < 0.1, Esc = 0.5 * P.Csc * P.Vmin^2; end
    [E2, S2, fl] = sr_bank_step(Esc, SOC, Pdc, Pl, P, dt);
    M(n, :) = [Esc, SOC, Pdc, Pl, dt, E2, S2, fl.Psc, fl.Pch, fl.Pdis, fl.Pdump, fl.Punserved, fl.Pbloss];
end
writematrix(M, fullfile(dir, 'bank.csv'));
end

function F_star = lpv_force(x, p, m_hat, P)
% same code as the Simulink block 'LPV state feedback + preview (100 Hz)' (build_stage3.m), C3
mg = P.Kgrid_m;  nL = numel(mg);
i = 1;  a = 0;
if m_hat >= mg(nL)
    i = nL - 1;  a = 1;
elseif m_hat > mg(1)
    for k = 1:nL - 1
        if m_hat >= mg(k) && m_hat <= mg(k + 1)
            i = k;  a = (m_hat - mg(k)) / (mg(k + 1) - mg(k));
        end
    end
end
Kx = reshape((1 - a) * P.Kx(i, :) + a * P.Kx(i + 1, :), 2, 8);
np = size(P.Kp, 2) / 2;
Kp = reshape((1 - a) * P.Kp(i, :) + a * P.Kp(i + 1, :), 2, np);
F_star = -Kx * x - Kp * p;
end
